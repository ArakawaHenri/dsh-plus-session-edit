import { writeFile, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { build } from 'esbuild';

const root = new URL('../', import.meta.url);

async function assertLocaleParity() {
  const [en, zh] = await Promise.all([
    readFile(new URL('locale/en.json', root), 'utf8'),
    readFile(new URL('locale/zh.json', root), 'utf8'),
  ]);
  const enKeys = Object.keys(JSON.parse(en)).sort();
  const zhKeys = Object.keys(JSON.parse(zh)).sort();
  if (JSON.stringify(enKeys) !== JSON.stringify(zhKeys)) throw new Error('Client locale keys must match');
}

// Tests use this pure build result without writing or racing the generated root client.js.
export async function buildClientSource() {
  await assertLocaleParity();
  const result = await build({
    entryPoints: [fileURLToPath(new URL('src/client.entry.js', root))],
    bundle: true,
    format: 'iife',
    target: 'es2022',
    loader: { '.css': 'text' },
    legalComments: 'none',
    write: false,
  });
  return `// Generated by scripts/build-client.js from src/client.entry.js. Edit that file and its imports.\n${result.outputFiles[0].text}`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const source = await buildClientSource();
  const output = new URL('client.js', root);
  if (process.argv.includes('--check')) {
    const current = await readFile(output, 'utf8');
    if (source !== current) throw new Error('client.js is stale; run node scripts/build-client.js');
  } else {
    await writeFile(output, source);
    console.log('Built client.js');
  }
}
